import numpy as np


def softmax_loss_naive(W, X, y, reg):
    """
    Функция потерь softmax, наивная реализация (с циклами)

    Входы имеют размерность D, число классов — C, вычисления ведутся над
    мини-батчами из N примеров.

    Входные данные:
    - W: массив numpy формы (D, C) с весами.
    - X: массив numpy формы (N, D) — мини-батч данных.
    - y: массив numpy формы (N,) с обучающими метками; y[i] = c означает,
      что X[i] имеет метку c, где 0 <= c < C.
    - reg: (float) коэффициент регуляризации

    Возвращает кортеж из:
    - значения функции потерь (одно число типа float)
    - градиента по весам W — массива той же формы, что и W
    """
    # Инициализируем значение потерь и градиент нулями.
    loss = 0.0
    dW = np.zeros_like(W)

    # вычисляем значение функции потерь и градиент
    num_classes = W.shape[1]
    num_train = X.shape[0]
    for i in range(num_train):
        scores = X[i].dot(W)

        # вычисляем вероятности численно устойчивым способом
        scores -= np.max(scores)
        p = np.exp(scores)
        p /= p.sum()  # нормировка
        logp = np.log(p)

        loss -= logp[y[i]]  # потери — это отрицательный логарифм вероятности

        # Градиент по весам
        for j in range(num_classes):
            if j == y[i]:
                dW[:, j] += (p[j] - 1) * X[i]
            else:
                dW[:, j] += p[j] * X[i]


    # усредняем потери по примерам и добавляем регуляризацию
    loss = loss / num_train + reg * np.sum(W * W)
    
    # Средний градиент и градиент регуляризации
    dW = dW / num_train + 2 * reg * W

    #############################################################################
    # TODO:                                                                     #
    # Вычислите градиент функции потерь и сохраните его в dW.                   #
    # Вместо того чтобы сначала вычислять потери, а затем производную,          #
    # может оказаться проще вычислять производную одновременно с потерями.      #
    # Поэтому, возможно, придётся изменить часть кода выше, чтобы вычислить     #
    # градиент.                                                                 #
    #############################################################################


    return loss, dW


def softmax_loss_vectorized(W, X, y, reg):
    """
    Функция потерь softmax, векторизованная версия.

    Входные и выходные данные — такие же, как у softmax_loss_naive.
    """
    # Инициализируем значение потерь и градиент нулями.
    loss = 0.0
    dW = np.zeros_like(W)


    #############################################################################
    # TODO:                                                                     #
    # Реализуйте векторизованную версию функции потерь softmax и сохраните      #
    # результат в loss.                                                         #
    #############################################################################
    num_train = X.shape[0]

    # Оценки всех классов для всех объектов
    scores = X.dot(W)

    # Численная устойчивость: вычитаем максимум из каждой строки
    scores -= np.max(scores, axis=1, keepdims=True)

    # Преобразуем оценки в вероятности
    exp_scores = np.exp(scores)
    probs = exp_scores / np.sum(exp_scores, axis=1, keepdims=True)

    # Вероятности правильных классов
    correct_class_probs = probs[np.arange(num_train), y]

    # Средняя потеря и регуляризация
    loss = np.mean(-np.log(correct_class_probs))
    loss += reg * np.sum(W * W)

    #############################################################################
    # TODO:                                                                     #
    # Реализуйте векторизованное вычисление градиента функции потерь softmax    #
    # и сохраните результат в dW.                                               #
    #                                                                           #
    # Подсказка: вместо того чтобы вычислять градиент с нуля, может оказаться   #
    # проще переиспользовать промежуточные значения, полученные при             #
    # вычислении потерь.                                                        #
    #############################################################################
    dscores = probs.copy()
    dscores[np.arange(num_train), y] -= 1
    dscores /= num_train

    dW = X.T.dot(dscores)
    dW += 2 * reg * W
    
    return loss, dW
